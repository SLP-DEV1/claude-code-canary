import { access, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { createInterface } from 'node:readline/promises';
import YAML from 'yaml';
import { explainSuiteSelection, parseSuite, type ScenarioSuite } from './suite.js';

const DEFAULT_OUTPUT = '.canary/release.suite.yml';
const DEFAULT_INCLUDES = ['.canary/**/*.canary.yml', '.canary/**/*.canary.yaml'];
const DEFAULT_CONCURRENCY = 1;
const DEFAULT_MAX_RUNS = 500;

export interface SuiteInitOptions {
  cwd?: string;
  output?: string;
  name?: string;
  include?: string[];
  concurrency?: number;
  maxRuns?: number;
  failFast?: boolean;
  reuseResults?: boolean;
  force?: boolean;
  dryRun?: boolean;
}

export interface SuiteInitResult {
  name: string;
  output: string;
  outputPath: string;
  scenarioCount: number;
  scenarios: string[];
  suite: ScenarioSuite;
  yaml: string;
  written: boolean;
}

function normalizeRelative(value: string): string {
  return value.split(path.sep).join('/');
}

async function exists(target: string): Promise<boolean> {
  try {
    await access(target);
    return true;
  } catch {
    return false;
  }
}

function assertInsideWorkspace(root: string, target: string): void {
  const relative = path.relative(root, target);
  if (!relative || relative === '.') throw new Error('Suite output must be a file inside the workspace.');
  if (path.isAbsolute(relative) || relative === '..' || relative.startsWith(`..${path.sep}`)) {
    throw new Error(`Suite output must stay inside the workspace: ${target}`);
  }
}

function positiveInteger(value: number, label: string, max?: number): number {
  if (!Number.isInteger(value) || value < 1 || (max !== undefined && value > max)) {
    throw new Error(`${label} must be a positive integer${max ? ` up to ${max}` : ''}.`);
  }
  return value;
}

async function inferSuiteName(root: string): Promise<string> {
  try {
    const parsed = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8')) as { name?: unknown };
    if (typeof parsed.name === 'string' && parsed.name.trim()) {
      const parts = parsed.name.trim().split('/');
      return parts[parts.length - 1] || 'release';
    }
  } catch {
    // A package.json is optional. Fall back to the workspace directory name.
  }
  return path.basename(root) || 'release';
}

function suiteDefinition(options: {
  name: string;
  include: string[];
  concurrency: number;
  maxRuns: number;
  failFast: boolean;
  reuseResults: boolean;
}): ScenarioSuite {
  return parseSuite({
    version: 1,
    name: options.name,
    include: options.include,
    concurrency: options.concurrency,
    fail_fast: options.failFast,
    max_runs: options.maxRuns,
    reuse_results: options.reuseResults,
  });
}

export async function initializeSuite(options: SuiteInitOptions = {}): Promise<SuiteInitResult> {
  const root = path.resolve(options.cwd ?? process.cwd());
  const output = options.output?.trim() || DEFAULT_OUTPUT;
  const outputPath = path.resolve(root, output);
  assertInsideWorkspace(root, outputPath);

  if (!/\.ya?ml$/i.test(outputPath)) throw new Error('Suite output must use a .yml or .yaml extension.');
  if (await exists(outputPath) && !options.force) {
    throw new Error(`Suite already exists: ${normalizeRelative(path.relative(root, outputPath))}. Use --force to replace it.`);
  }

  const name = options.name?.trim() || await inferSuiteName(root);
  const include = (options.include ?? DEFAULT_INCLUDES).map((item) => item.trim()).filter(Boolean);
  if (include.length === 0) throw new Error('At least one suite include pattern is required.');

  const concurrency = positiveInteger(options.concurrency ?? DEFAULT_CONCURRENCY, 'concurrency', 32);
  const requestedMaxRuns = positiveInteger(options.maxRuns ?? DEFAULT_MAX_RUNS, 'max-runs', 10_000);
  const failFast = options.failFast ?? false;
  const reuseResults = options.reuseResults ?? false;

  let suite = suiteDefinition({ name, include, concurrency, maxRuns: requestedMaxRuns, failFast, reuseResults });
  const selection = await explainSuiteSelection(suite, { cwd: root });

  if (options.maxRuns === undefined && selection.discovered.length > suite.max_runs) {
    suite = suiteDefinition({
      name,
      include,
      concurrency,
      maxRuns: Math.min(10_000, selection.discovered.length),
      failFast,
      reuseResults,
    });
  }

  const yaml = `# Generated by claude-canary suite init\n${YAML.stringify(suite)}`;
  if (!options.dryRun) {
    await mkdir(path.dirname(outputPath), { recursive: true });
    await writeFile(outputPath, yaml, 'utf8');
  }

  return {
    name: suite.name,
    output: normalizeRelative(path.relative(root, outputPath)),
    outputPath,
    scenarioCount: selection.discovered.length,
    scenarios: selection.discovered.map((item) => item.path),
    suite,
    yaml,
    written: !options.dryRun,
  };
}

function hasFlag(args: string[], name: string): boolean {
  return args.includes(name);
}

function valueAfter(args: string[], name: string): string | undefined {
  const index = args.indexOf(name);
  if (index < 0) return undefined;
  const value = args[index + 1];
  if (!value || value.startsWith('--')) throw new Error(`${name} requires a value.`);
  return value;
}

function valuesAfter(args: string[], name: string): string[] | undefined {
  const values: string[] = [];
  for (let index = 0; index < args.length; index += 1) {
    if (args[index] !== name) continue;
    const value = args[index + 1];
    if (!value || value.startsWith('--')) throw new Error(`${name} requires a value.`);
    values.push(...value.split(',').map((item) => item.trim()).filter(Boolean));
    index += 1;
  }
  return values.length ? values : undefined;
}

function numberAfter(args: string[], name: string, fallback: number, max?: number): number {
  const raw = valueAfter(args, name);
  if (raw === undefined) return fallback;
  const value = Number(raw);
  return positiveInteger(value, name.replace(/^--/, ''), max);
}

function suiteInitHelp(): string {
  return `Initialize a Canary scenario suite.\n\n` +
    `Usage:\n` +
    `  claude-canary suite init [options]\n\n` +
    `Options:\n` +
    `  --output <file>       Suite file (default: ${DEFAULT_OUTPUT})\n` +
    `  --name <name>         Suite name (default: package/workspace name)\n` +
    `  --include <glob>      Scenario glob; repeat or comma-separate values\n` +
    `  --concurrency <n>     Parallel scenarios, 1-32 (default: ${DEFAULT_CONCURRENCY})\n` +
    `  --max-runs <n>        Run budget, up to 10000 (default: ${DEFAULT_MAX_RUNS})\n` +
    `  --fail-fast           Stop after the first failure\n` +
    `  --reuse-results       Reuse safe cached results when possible\n` +
    `  --force               Replace an existing suite file\n` +
    `  --dry-run             Print the generated YAML without writing it\n` +
    `  --yes                 Use defaults without interactive prompts\n` +
    `  --json                Print the result as JSON\n` +
    `  --help                Show this help\n`;
}

async function ask(question: string, fallback: string, rl: ReturnType<typeof createInterface>): Promise<string> {
  const answer = (await rl.question(`${question} [${fallback}]: `)).trim();
  return answer || fallback;
}

async function confirm(question: string, fallback: boolean, rl: ReturnType<typeof createInterface>): Promise<boolean> {
  const marker = fallback ? 'Y/n' : 'y/N';
  const answer = (await rl.question(`${question} [${marker}]: `)).trim().toLowerCase();
  if (!answer) return fallback;
  if (['y', 'yes'].includes(answer)) return true;
  if (['n', 'no'].includes(answer)) return false;
  throw new Error(`Expected yes or no for: ${question}`);
}

export async function runSuiteInitCli(args: string[]): Promise<void> {
  if (hasFlag(args, '--help') || hasFlag(args, '-h')) {
    console.log(suiteInitHelp());
    return;
  }

  const cwd = process.cwd();
  let output = valueAfter(args, '--output') ?? DEFAULT_OUTPUT;
  let name = valueAfter(args, '--name');
  let include = valuesAfter(args, '--include');
  let concurrency = numberAfter(args, '--concurrency', DEFAULT_CONCURRENCY, 32);
  let maxRuns = numberAfter(args, '--max-runs', DEFAULT_MAX_RUNS, 10_000);
  let failFast = hasFlag(args, '--fail-fast');
  let reuseResults = hasFlag(args, '--reuse-results');
  let force = hasFlag(args, '--force');
  const dryRun = hasFlag(args, '--dry-run');
  const json = hasFlag(args, '--json');
  const interactive = !hasFlag(args, '--yes') && process.stdin.isTTY === true && process.stdout.isTTY === true;

  if (interactive) {
    const rl = createInterface({ input: process.stdin, output: process.stdout });
    try {
      const inferredName = name ?? await inferSuiteName(cwd);
      output = await ask('Suite file', output, rl);
      name = await ask('Suite name', inferredName, rl);
      const includeText = await ask('Scenario include glob(s), comma-separated', (include ?? DEFAULT_INCLUDES).join(', '), rl);
      include = includeText.split(',').map((item) => item.trim()).filter(Boolean);
      concurrency = Number(await ask('Concurrency', String(concurrency), rl));
      maxRuns = Number(await ask('Maximum run budget', String(maxRuns), rl));
      positiveInteger(concurrency, 'concurrency', 32);
      positiveInteger(maxRuns, 'max-runs', 10_000);
      failFast = await confirm('Enable fail-fast?', failFast, rl);
      reuseResults = await confirm('Reuse safe cached results?', reuseResults, rl);
      const target = path.resolve(cwd, output);
      if (await exists(target) && !force) {
        force = await confirm(`Replace existing ${normalizeRelative(path.relative(cwd, target))}?`, false, rl);
        if (!force) {
          console.log('Suite initialization cancelled.');
          return;
        }
      }
    } finally {
      rl.close();
    }
  }

  const result = await initializeSuite({ cwd, output, name, include, concurrency, maxRuns, failFast, reuseResults, force, dryRun });
  if (json) {
    console.log(JSON.stringify(result, null, 2));
    return;
  }
  if (dryRun) {
    console.log(result.yaml);
    console.error(`Discovered ${result.scenarioCount} scenario(s). No file written.`);
    return;
  }
  console.log(`Created ${result.output}`);
  console.log(`Discovered ${result.scenarioCount} scenario(s).`);
  console.log(`Next: claude-canary suite ${result.output} --list`);
}
