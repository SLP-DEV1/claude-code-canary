import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import type { PluginDiscovery } from '../src/plugin-init.js';
import type { PluginMatrixResult } from '../src/plugin-matrix.js';
import {
  aggregatePluginSuiteMatrices,
  assertGeneratedPluginSuiteCoverage,
  assertGeneratedPluginSuiteFresh,
  expectedGeneratedPluginSuiteScenarioIds,
  formatPluginSuiteMarkdown,
  loadGeneratedPluginSuite,
  runPluginSuite,
  validatePluginSuiteRunBudget,
  type PluginSuiteScenario,
} from '../src/plugin-suite.js';

const roots: string[] = [];

async function tempRoot(): Promise<string> {
  const root = await mkdtemp(path.join(tmpdir(), 'canary-plugin-suite-test-'));
  roots.push(root);
  return root;
}

afterEach(async () => {
  await Promise.all(roots.splice(0).map((root) => rm(root, { recursive: true, force: true })));
});

const scenarioYaml = (name: string) => `version: 1\nname: ${name}\nprompt: Read only.\n`;

function suiteScenario(id: string, kind: PluginSuiteScenario['kind']): PluginSuiteScenario {
  return {
    id,
    kind,
    component: kind === 'load' ? undefined : id.split('-', 2)[1],
    path: `.canary/plugins/demo-plugin/${id}.canary.yml`,
    scenario: {
      version: 1,
      name: `plugin-demo-plugin-${id}`,
      prompt: 'Read only.',
      claude: {
        executable: 'claude',
        args: [],
        include_hook_events: false,
        timeout_seconds: 900,
        env: {},
      },
    },
  };
}

function matrix(scenario: PluginSuiteScenario, passFirst: boolean, passSecond: boolean): PluginMatrixResult {
  const versions = ['2.1.9', '2.1.10'];
  const passed = [passFirst, passSecond];
  const entries = versions.map((version, index) => ({
    version,
    passed: passed[index],
    failures: passed[index] ? [] : [`${scenario.id} failed`],
    durationMs: 100 + index,
    toolCalls: index + 1,
    totalTokens: 1000 + index,
    costUsd: 0.01 + index * 0.01,
  }));
  return {
    schemaVersion: 1,
    kind: 'plugin-compatibility-matrix',
    canaryVersion: '0.1.0',
    scenario: scenario.scenario.name,
    pluginName: 'demo-plugin',
    gitCommit: '0123456789abcdef0123456789abcdef01234567',
    versions,
    entries,
    compatible: entries.filter((entry) => entry.passed).length,
    incompatible: entries.filter((entry) => !entry.passed).length,
    firstIncompatibleVersion: entries.find((entry) => !entry.passed)?.version,
    createdAt: '2026-08-27T00:00:00.000Z',
  };
}

function discovery(root: string): PluginDiscovery {
  return {
    schemaVersion: 1,
    pluginName: 'demo-plugin',
    pluginRoot: path.join(root, 'plugin'),
    manifestPath: '.claude-plugin/plugin.json',
    commands: [{ kind: 'command', name: 'hello', path: 'commands/hello.md', source: 'default', description: 'Hello' }],
    agents: [],
    skills: [],
    hooks: [],
    mcpServers: [],
    warnings: [],
  };
}

async function writeDiscoveryFile(suite: string, value: PluginDiscovery): Promise<void> {
  const portable = { ...value, pluginRoot: '../plugin' };
  await writeFile(path.join(suite, 'discovery.json'), `${JSON.stringify(portable, null, 2)}\n`, 'utf8');
}

describe('plugin compatibility suites', () => {
  it('loads Canary-generated scenarios in stable component order', async () => {
    const root = await tempRoot();
    const suite = path.join(root, 'suite');
    await mkdir(suite, { recursive: true });
    await writeFile(path.join(suite, '.claude-canary-plugin-init'), 'Generated by claude-canary plugin-init.\n', 'utf8');
    await writeFile(path.join(suite, 'skill-guide.canary.yml'), scenarioYaml('skill-guide'), 'utf8');
    await writeFile(path.join(suite, 'load.canary.yml'), scenarioYaml('load'), 'utf8');
    await writeFile(path.join(suite, 'command-review.canary.yml'), scenarioYaml('command-review'), 'utf8');
    await writeFile(path.join(suite, 'hook-stop.canary.yml'), scenarioYaml('hook-stop'), 'utf8');

    const loaded = await loadGeneratedPluginSuite(suite);
    expect(loaded.map((entry) => entry.id)).toEqual(['load', 'command-review', 'skill-guide', 'hook-stop']);
    expect(loaded.map((entry) => entry.kind)).toEqual(['load', 'command', 'skill', 'hook']);
  });

  it('refuses unmarked directories and protects the default run budget', async () => {
    const root = await tempRoot();
    const suite = path.join(root, 'suite');
    await mkdir(suite, { recursive: true });
    await writeFile(path.join(suite, 'load.canary.yml'), scenarioYaml('load'), 'utf8');
    await expect(loadGeneratedPluginSuite(suite)).rejects.toThrow(/marker/i);

    expect(validatePluginSuiteRunBudget(8, 10)).toBe(80);
    expect(() => validatePluginSuiteRunBudget(21, 10)).toThrow(/210 Claude runs/i);
    expect(validatePluginSuiteRunBudget(21, 10, 250)).toBe(210);
    expect(() => validatePluginSuiteRunBudget(1, 1, 1001)).toThrow(/between 1 and 1000/i);
  });

  it('rejects stale or wrong-plugin generated suites', async () => {
    const root = await tempRoot();
    const suite = path.join(root, 'suite');
    await mkdir(suite, { recursive: true });
    const live = discovery(root);
    await writeDiscoveryFile(suite, live);
    await expect(assertGeneratedPluginSuiteFresh(suite, live)).resolves.toBeUndefined();

    const changed: PluginDiscovery = {
      ...live,
      commands: [...live.commands, { kind: 'command', name: 'new-command', path: 'commands/new-command.md', source: 'default' }],
    };
    await expect(assertGeneratedPluginSuiteFresh(suite, changed)).rejects.toThrow(/stale/i);

    await writeDiscoveryFile(suite, { ...live, pluginName: 'other-plugin' });
    await expect(assertGeneratedPluginSuiteFresh(suite, live)).rejects.toThrow(/belongs to plugin other-plugin/i);
  });

  it('requires every generated component scenario while allowing custom extras', () => {
    const live = discovery('/tmp/demo');
    expect(expectedGeneratedPluginSuiteScenarioIds(live)).toEqual(['load', 'command-hello']);

    const load = suiteScenario('load', 'load');
    expect(() => assertGeneratedPluginSuiteCoverage([load], live)).toThrow(/missing 1 expected scenario.*command-hello/i);

    const command = suiteScenario('command-hello', 'command');
    const custom = suiteScenario('custom-extra', 'custom');
    expect(() => assertGeneratedPluginSuiteCoverage([load, command, custom], live)).not.toThrow();
  });

  it('aggregates a full release-by-scenario compatibility matrix', () => {
    const load = suiteScenario('load', 'load');
    const command = suiteScenario('command-review', 'command');
    const result = aggregatePluginSuiteMatrices(
      'demo-plugin',
      '.canary/plugins/demo-plugin',
      ['2.1.9', '2.1.10'],
      [
        { suiteScenario: load, matrix: matrix(load, true, true) },
        { suiteScenario: command, matrix: matrix(command, true, false) },
      ],
    );

    expect(result.totalRuns).toBe(4);
    expect(result.compatibleRuns).toBe(3);
    expect(result.incompatibleRuns).toBe(1);
    expect(result.compatibleVersions).toBe(1);
    expect(result.incompatibleVersions).toBe(1);
    expect(result.firstIncompatibleVersion).toBe('2.1.10');
    expect(result.versionResults[1]?.failedScenarios).toBe(1);
    expect(result.versionResults[1]?.failures[0]?.scenarioId).toBe('command-review');

    const markdown = formatPluginSuiteMarkdown(result);
    expect(markdown).toContain('Full compatibility matrix');
    expect(markdown).toContain('| `2.1.9` | ✅ | ✅ | ✅ Compatible |');
    expect(markdown).toContain('| `2.1.10` | ✅ | ❌ | ❌ 1 failed |');
    expect(markdown).toContain('command-review failed');
    expect(markdown).toContain('Runs: **4** · Passed: **3** · Failed: **1**');
  });

  it('refuses aggregation when matrices used different release sets', () => {
    const load = suiteScenario('load', 'load');
    const bad = matrix(load, true, true);
    bad.versions = ['2.1.9'];
    bad.entries = bad.entries.slice(0, 1);
    expect(() => aggregatePluginSuiteMatrices(
      'demo-plugin',
      '.canary/plugins/demo-plugin',
      ['2.1.9', '2.1.10'],
      [{ suiteScenario: load, matrix: bad }],
    )).toThrow(/exact selected release set/i);
  });

  it('orchestrates every generated scenario with one fixed release set', async () => {
    const root = await tempRoot();
    const plugin = path.join(root, 'plugin');
    const suite = path.join(root, 'suite');
    await mkdir(path.join(plugin, '.claude-plugin'), { recursive: true });
    await mkdir(path.join(plugin, 'commands'), { recursive: true });
    await mkdir(suite, { recursive: true });
    await writeFile(path.join(plugin, '.claude-plugin', 'plugin.json'), JSON.stringify({ name: 'demo-plugin' }), 'utf8');
    await writeFile(path.join(plugin, 'commands', 'hello.md'), '---\ndescription: Hello\n---\nSay hello.\n', 'utf8');
    await writeFile(path.join(suite, '.claude-canary-plugin-init'), 'Generated by claude-canary plugin-init.\n', 'utf8');
    await writeDiscoveryFile(suite, discovery(root));
    await writeFile(path.join(suite, 'load.canary.yml'), scenarioYaml('plugin-demo-plugin-load'), 'utf8');
    await writeFile(path.join(suite, 'command-hello.canary.yml'), scenarioYaml('plugin-demo-plugin-command-hello'), 'utf8');

    const calls: string[] = [];
    const result = await runPluginSuite({
      cwd: root,
      pluginPath: 'plugin',
      suiteDir: 'suite',
      versions: ['2.1.9', '2.1.10'],
      writeArtifacts: false,
      matrixRunner: async (scenario, options) => {
        calls.push(scenario.name);
        expect(options.versions).toEqual(['2.1.9', '2.1.10']);
        const synthetic = suiteScenario(scenario.name.endsWith('load') ? 'load' : 'command-hello', scenario.name.endsWith('load') ? 'load' : 'command');
        synthetic.scenario = scenario;
        return matrix(synthetic, true, true);
      },
    });

    expect(calls).toEqual(['plugin-demo-plugin-load', 'plugin-demo-plugin-command-hello']);
    expect(result.totalRuns).toBe(4);
    expect(result.incompatibleRuns).toBe(0);
    expect(result.jsonArtifactPath).toBeUndefined();
    expect(result.scenarios.map((entry) => entry.path)).toEqual(['suite/load.canary.yml', 'suite/command-hello.canary.yml']);
  });
});
