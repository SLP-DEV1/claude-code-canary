import { access, mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { initializeSuite } from '../src/suite-init.js';
import { loadSuite } from '../src/suite.js';

async function exists(file: string): Promise<boolean> {
  try {
    await access(file);
    return true;
  } catch {
    return false;
  }
}

async function workspace(): Promise<string> {
  const root = await mkdtemp(path.join(tmpdir(), 'canary-suite-init-'));
  await mkdir(path.join(root, '.canary'), { recursive: true });
  await writeFile(path.join(root, 'package.json'), '{"name":"demo-workspace"}\n', 'utf8');
  await writeFile(
    path.join(root, '.canary', 'smoke.canary.yml'),
    'version: 1\nname: smoke\nprompt: verify the workspace\ntags: [release]\n',
    'utf8',
  );
  return root;
}

describe('suite init', () => {
  it('creates a validated suite and discovers existing scenarios', async () => {
    const root = await workspace();
    try {
      const result = await initializeSuite({ cwd: root });
      expect(result.name).toBe('demo-workspace');
      expect(result.output).toBe('.canary/release.suite.yml');
      expect(result.scenarioCount).toBe(1);
      expect(result.scenarios).toEqual(['.canary/smoke.canary.yml']);
      expect(result.yaml).toContain('Generated by claude-canary suite init');

      const suite = await loadSuite(path.join(root, result.output));
      expect(suite.name).toBe('demo-workspace');
      expect(suite.include).toEqual(['.canary/**/*.canary.yml', '.canary/**/*.canary.yaml']);
      expect(suite.concurrency).toBe(1);
      expect(suite.max_runs).toBe(500);
    } finally {
      await rm(root, { recursive: true, force: true });
    }
  });

  it('refuses to overwrite an existing suite unless force is enabled', async () => {
    const root = await workspace();
    try {
      await initializeSuite({ cwd: root });
      await expect(initializeSuite({ cwd: root })).rejects.toThrow('Suite already exists');
      const replaced = await initializeSuite({ cwd: root, force: true, name: 'replacement' });
      expect(replaced.name).toBe('replacement');
      expect(await readFile(path.join(root, replaced.output), 'utf8')).toContain('name: replacement');
    } finally {
      await rm(root, { recursive: true, force: true });
    }
  });

  it('supports dry-run generation without touching the workspace', async () => {
    const root = await workspace();
    try {
      const result = await initializeSuite({ cwd: root, dryRun: true, name: 'preview', concurrency: 2, maxRuns: 25 });
      expect(result.written).toBe(false);
      expect(result.suite.concurrency).toBe(2);
      expect(result.suite.max_runs).toBe(25);
      expect(await exists(path.join(root, result.output))).toBe(false);
    } finally {
      await rm(root, { recursive: true, force: true });
    }
  });

  it('blocks suite output outside the workspace', async () => {
    const root = await workspace();
    try {
      await expect(initializeSuite({ cwd: root, output: '../outside.suite.yml' })).rejects.toThrow('must stay inside the workspace');
    } finally {
      await rm(root, { recursive: true, force: true });
    }
  });
});
